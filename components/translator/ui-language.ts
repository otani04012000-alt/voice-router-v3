export const UI_LANGUAGES: { value: UiLanguage; label: string }[] = [
  { value: "ja", label: "日本語" },
  { value: "zh", label: "中文" },
  { value: "vi", label: "Tiếng Việt" },
  { value: "km", label: "ភាសាខ្មែរ" },
];

export function isUiLanguage(value: unknown): value is UiLanguage {
  return typeof value === "string" && UI_LANGUAGES.some((item) => item.value === value);
}

export function resolveUiLanguage(query: URLSearchParams, saved: string | null, browserLanguage: string): UiLanguage {
  const candidates = [query.get("ui"), query.get("from"), saved, browserLanguage.split("-")[0]];
  return candidates.find(isUiLanguage) || "ja";
}

